suppressMessages({
    library(mlr3verse)
    library(mlr3proba)
    library(mlr3extralearners)
    library(data.table)
    library(survjdr)
})

blocks = c("cnv", "mirna", "mutation", "rna")
internal_seed = 123
cv_save_path = "~/scratch_MS/legoff/benchmark/results/cv_logs/SJIVE_woClin"
learners = list()

rankJ = c(0, 1, 5, 10)
rankA = c(0, 1, 5, 10)
eta = c(0.1, 0.5, 0.9)
params_comb = expand.grid(rankJ=rankJ, rankA=rankA, eta=eta)
params_comb = params_comb[!(params_comb$rankJ==0 & params_comb$rankA==0),]
#print(as.factor(params_comb$pred_mode))
for (i in 1:nrow(params_comb)) {
    learners <- c(learners,
        lrn(
            "surv.sjive",
            blocks=blocks,
            rankJ=params_comb[i, "rankJ"],
            rankA=params_comb[i, "rankA"],
            eta=params_comb[i, "eta"],
            clinical_fav=FALSE,
            CV_measure="V&VH",
            nlambdas=100,
            nfolds=10,
            cv_save_path=cv_save_path,
            max.iter=2000,
            seed=internal_seed,
            id=paste0("sjive_j", params_comb[i, "rankJ"],
                      "_a", params_comb[i, "rankA"], "_eta",
                      params_comb[i, "eta"])
        )
    )
}

